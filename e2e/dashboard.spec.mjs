import { test, expect } from '@playwright/test';

test('Métricas, filtros, orden, tema persistente y diseño adaptable', async ({ page }, testInfo) => {
  const errores = [];
  page.on('pageerror', error => errores.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Cifras claras. Mejores decisiones.' })).toBeVisible();
  await expect(page.locator('.featured .metric-value')).toContainText(/2.?343,00/);
  await expect(page.locator('.metric-value').nth(1)).toHaveText('60');
  await expect(page.locator('.metric-value').nth(2)).toHaveText('150');
  await expect(page.locator('tbody tr')).toHaveCount(10);
  await page.getByRole('button', { name: 'Incidencias', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(5);
  await page.getByRole('searchbox').fill('V063');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await expect(page.locator('tbody')).toContainText('Producto inexistente');
  await page.getByRole('searchbox').fill('no-existe');
  await expect(page.locator('tbody')).toContainText('No hay registros que coincidan');
  await page.getByRole('searchbox').fill('');
  await page.getByRole('button', { name: 'Todos', exact: true }).click();
  await page.getByRole('combobox').selectOption('nombre');
  await expect(page.locator('.category-label').first()).toContainText('Deporte');
  await page.getByRole('combobox').selectOption('ingresos');
  await expect(page.locator('.category-label').first()).toContainText('Hogar');
  await page.locator('.day-column').nth(2).click();
  await expect(page.locator('.day-column').nth(2)).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Activar modo oscuro' }).click();
  await expect(page.locator('.dashboard')).toHaveAttribute('data-theme', 'dark');
  await page.reload();
  await expect(page.locator('.dashboard')).toHaveAttribute('data-theme', 'dark');
  await page.getByRole('button', { name: 'Activar modo claro' }).click();
  await expect(page.locator('.dashboard')).toHaveAttribute('data-theme', 'light');
  const respuesta = await page.request.get('/datos/resumen.json');
  expect(respuesta.ok()).toBeTruthy();
  expect((await respuesta.json()).ingresos_totales).toBe(2343);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  expect(errores).toEqual([]);
  await page.screenshot({ path: `evidencias/dashboard-${testInfo.project.name}.png`, fullPage: true });
});
